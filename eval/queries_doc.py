"""Write docs/queries.md from the Cypher query constants in the code. Nothing is typed.

Run: uv run python -m eval.queries_doc
The test tests/unit/test_queries_doc.py rebuilds the text and fails if docs/queries.md
differs, so the doc cannot drift from the code. Add a query here when a new module
starts to depend on one.
"""

import importlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "queries.md"

# (module, constant, what it is for). The constant is read from the module at build time.
REGISTRY = [
    ("core.detectors.pressure", "CLAIMS_QUERY", "Pressure: claims as of T (spec 7.1)"),
    ("core.detectors.vouch", "CLAIMS_QUERY", "Vouch: claims as of T (spec 7.1)"),
    ("core.detectors.vouch", "SHARES_QUERY", "Vouch: SHARES edges as of T (spec 7.1)"),
    ("core.detectors.rush", "GRANTS_QUERY", "Rush: grants as of T (spec 7.1)"),
    ("core.detectors.rush", "FIRST_ACTION_QUERY", "Rush: first action by a keeper (spec 7.1)"),
    ("core.detectors.low_history", "HISTORY_QUERY", "Low history: prior actions for an actor"),
    ("core.takeover.cost", "PATH_QUERY", "Takeover cost: SPpaths from the outsider (spec 2.2)"),
    ("core.takeover.cost", "ENTRY_QUERY", "Takeover cost: entry points (spec 2.2)"),
    ("core.takeover.guardians", "PROJECTION", "Guardians: flow network projection (spec 2.2, 7.4)"),
    ("core.takeover.guardians", "GUARDIANS_QUERY", "Guardians: min-cut query, maxFlow (spec 7.4)"),
    (
        "packs.oss.ecosystem.gaps",
        "GAP_QUERY",
        "Visibility gaps, UNREACHABLE / UNNOTICED (spec 7.5)",
    ),
    ("redteam.load_tallowdate", "Q_ACTORS", "Synthetic tallowdate load: actors (spec 3.5)"),
    ("redteam.load_tallowdate", "Q_ACTIONS", "Synthetic tallowdate load: actions (spec 3.5)"),
    ("redteam.load_tallowdate", "Q_RELEASES", "Synthetic tallowdate load: releases (spec 3.5)"),
]


def build() -> str:
    lines = [
        "# Cypher queries the product depends on",
        "",
        "Generated by `uv run python -m eval.queries_doc` from the query constants in the code.",
        "Do not edit by hand: `tests/unit/test_queries_doc.py` fails when they disagree.",
        "",
        "The project rule (CLAUDE.md): an explicit timeout on every query, on FalkorDB 6.0.2.",
        "Writes use MERGE on unique keys. Exploratory reads go through the read-only guard",
        "(`core/graph/ro_guard.py`).",
        "",
        "| # | Constant | Module | Used for |",
        "|---|---|---|---|",
    ]
    for i, (mod, name, what) in enumerate(REGISTRY, 1):
        lines.append(f"| {i} | `{name}` | `{mod}` | {what} |")
    lines.append("")
    for i, (mod, name, what) in enumerate(REGISTRY, 1):
        text = getattr(importlib.import_module(mod), name)
        assert isinstance(text, str), f"{mod}.{name} is not a string query"
        lines += [f"## {i}. {name} ({mod})", "", what, "", "```cypher", text.rstrip(), "```", ""]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(REGISTRY)} queries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
